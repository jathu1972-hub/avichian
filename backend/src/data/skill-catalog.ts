export function skillSlug(categorySlug: string, skillName: string): string {
  const token = skillName
    .toLowerCase()
    .replace(/\+/g, "plus")
    .replace(/#/g, "sharp")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
  return `${categorySlug}--${token}`;
}
